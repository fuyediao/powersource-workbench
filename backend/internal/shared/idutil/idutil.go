// Package idutil provides a small RFC 4122 version 4 UUID generator, avoiding an
// external dependency for the few places that need random ids (media object keys
// and UPS transaction ids).
package idutil

import (
	"crypto/rand"
	"encoding/hex"
)

// UUIDv4 returns a random version-4 UUID string.
func UUIDv4() string {
	var b [16]byte
	_, _ = rand.Read(b[:])
	b[6] = (b[6] & 0x0f) | 0x40
	b[8] = (b[8] & 0x3f) | 0x80
	dst := make([]byte, 36)
	hex.Encode(dst[0:8], b[0:4])
	dst[8] = '-'
	hex.Encode(dst[9:13], b[4:6])
	dst[13] = '-'
	hex.Encode(dst[14:18], b[6:8])
	dst[18] = '-'
	hex.Encode(dst[19:23], b[8:10])
	dst[23] = '-'
	hex.Encode(dst[24:36], b[10:16])
	return string(dst)
}
